#!/usr/bin/env node
// Turn KanjiVG's kana files into src/lib/glyphs/kana-strokes.ts.
//
// KanjiVG (https://kanjivg.tagaini.net/, CC BY-SA 3.0, Ulrich Apel) draws every
// hiragana and katakana as one centreline path per stroke, in the taught order
// and direction, plus the spot where each stroke's number is printed -- exactly
// the shape of data the tracing engine wants. This script only moves it into
// the app's coordinate space: KanjiVG's 109-unit square is scaled to a 100-unit
// square sitting between the cap line (y = 10) and the baseline (y = 110) of
// the box the Latin letters use, and every path is rewritten in absolute
// commands so nothing downstream has to know where it came from.
//
//     # fetch the 92 source files somewhere outside the repo, then
//     node scripts/kanjivg_to_kana.mjs <dir-with-kanjivg-svgs>
//
// The source files are named by code point, e.g. 03042.svg for あ:
//     https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/03042.svg

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/lib/glyphs/kana-strokes.ts');

const dir = process.argv[2];
if (!dir) {
	console.error('usage: kanjivg_to_kana.mjs <dir-with-kanjivg-svgs>');
	process.exit(2);
}

const HIRAGANA = [
	...'あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん'
];
const KATAKANA = HIRAGANA.map((c) => String.fromCodePoint(c.codePointAt(0) + 0x60));

const SCALE = 100 / 109;
const DY = 10;
const X = (x) => x * SCALE;
const Y = (y) => y * SCALE + DY;
const f = (n) => String(Math.round(n * 100) / 100);

/** KanjiVG uses only M and relative c; anything else means the source changed. */
function absolute(d) {
	const tokens = d.match(/[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g) ?? [];
	let i = 0;
	let cmd = '';
	let x = 0;
	let y = 0;
	const out = [];
	const num = () => Number(tokens[i++]);
	while (i < tokens.length) {
		if (/[A-Za-z]/.test(tokens[i])) cmd = tokens[i++];
		if (cmd === 'M') {
			x = num();
			y = num();
			out.push(`M${f(X(x))} ${f(Y(y))}`);
			cmd = 'L';
		} else if (cmd === 'c' || cmd === 'C') {
			const rel = cmd === 'c';
			const p = [num(), num(), num(), num(), num(), num()];
			const ax = (k) => (rel ? x + p[k] : p[k]);
			const ay = (k) => (rel ? y + p[k] : p[k]);
			out.push(
				`C${f(X(ax(0)))} ${f(Y(ay(1)))} ${f(X(ax(2)))} ${f(Y(ay(3)))} ${f(X(ax(4)))} ${f(Y(ay(5)))}`
			);
			x = ax(4);
			y = ay(5);
		} else {
			throw new Error(`unexpected path command ${cmd} in ${d}`);
		}
	}
	return out.join(' ');
}

function load(ch) {
	const hex = ch.codePointAt(0).toString(16).padStart(5, '0');
	const svg = readFileSync(join(dir, `${hex}.svg`), 'utf8');
	const strokes = [...svg.matchAll(/<path id="kvg:[0-9a-f]+-s(\d+)"[^>]*\sd="([^"]+)"/g)]
		.sort((a, b) => Number(a[1]) - Number(b[1]))
		.map((m) => absolute(m[2]));
	const numbers = [
		...svg.matchAll(/<text transform="matrix\(1 0 0 1 ([\d.]+) ([\d.]+)\)">(\d+)<\/text>/g)
	]
		.sort((a, b) => Number(a[3]) - Number(b[3]))
		.map((m) => [Number(f(X(Number(m[1])))), Number(f(Y(Number(m[2]))))]);
	if (!strokes.length || strokes.length !== numbers.length)
		throw new Error(`${ch}: ${strokes.length} strokes but ${numbers.length} numbers`);
	return { strokes, numbers };
}

function table(name, chars, pick) {
	const lines = chars.map((c) => `\t'${c}': ${JSON.stringify(pick(load(c)))},`);
	return `export const ${name} = {\n${lines.join('\n')}\n};\n`;
}

const body = [
	'// Generated by scripts/kanjivg_to_kana.mjs from KanjiVG -- do not edit by hand.',
	'//',
	'// Stroke data (c) Ulrich Apel and the KanjiVG contributors, CC BY-SA 3.0',
	'// (https://kanjivg.tagaini.net/). Rescaled from its 109-unit square to the',
	"// app's 100-unit square at y 10-110 and rewritten in absolute commands; the",
	'// strokes, their order and their direction are unchanged. This file is under',
	'// the same licence. See CREDITS.md.',
	'',
	'type Table = Record<string, string[]>;',
	'type Numbers = Record<string, [number, number][]>;',
	'',
	table('HIRAGANA_STROKES', HIRAGANA, (g) => g.strokes).replace(' = {', ': Table = {'),
	table('KATAKANA_STROKES', KATAKANA, (g) => g.strokes).replace(' = {', ': Table = {'),
	'/** Where KanjiVG prints each stroke number: the left end of its baseline. */',
	table('STROKE_NUMBERS', [...HIRAGANA, ...KATAKANA], (g) => g.numbers).replace(
		' = {',
		': Numbers = {'
	)
].join('\n');

writeFileSync(OUT, body);
console.log(`wrote ${OUT}`);
